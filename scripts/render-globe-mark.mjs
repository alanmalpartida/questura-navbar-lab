#!/usr/bin/env node
// Generates the globe-badge variant's GlobeMark.tsx: `pnpm render-globe-mark`.
//
// A small vector globe for the member badge (22-28px). Natural Earth 1:110m
// land (world-atlas) in an orthographic view of the Atlantic, projected with
// d3-geo into a 64-unit viewBox. Islands too small to read at badge size are
// dropped. Shading, highlight and rim are SVG gradients, so the result is a
// few KB and sharp at any size.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { geoOrthographic, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const LON0 = -28, LAT0 = 22;     // same view as atlantic-4's globe
const MIN_AREA = 1.2;            // viewBox units^2; smaller islands are dropped
const OUT = join(import.meta.dirname, "..", "src", "navbars", "globe-badge", "shared", "components", "icons", "GlobeMark.tsx");

const modules = join(import.meta.dirname, "..", "node_modules");
const topo = JSON.parse(readFileSync(join(modules, "world-atlas", "land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const projection = geoOrthographic().rotate([-LON0, -LAT0]).scale(32).translate([32, 32]).clipAngle(90).precision(0.2);
const path = geoPath(projection).digits(1);

// Split the land into single polygons so each can be kept or dropped.
const polygons = land.features.flatMap((f) =>
  f.geometry.type === "MultiPolygon"
    ? f.geometry.coordinates.map((coordinates) => ({ type: "Polygon", coordinates }))
    : [f.geometry],
);
const kept = polygons.filter((p) => path.area(p) >= MIN_AREA);

// Draw through a context that collects the projected rings, then simplify
// each ring (Douglas-Peucker, TOLERANCE viewBox units): 1:110m is far more
// detail than 28px can show.
const rings = [];
const collector = {
  moveTo(x, y) { rings.push([[x, y]]); },
  lineTo(x, y) { rings.at(-1).push([x, y]); },
  closePath() {},
  arc() {},
};
const draw = geoPath(projection, collector);
for (const p of kept) draw(p);

const simplify = (pts, tol) => {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    let far = -1, dist = 0;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const dd = Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / len;
      if (dd > dist) { dist = dd; far = i; }
    }
    if (dist > tol) { keep[far] = 1; stack.push([a, far], [far, b]); }
  }
  return pts.filter((_, i) => keep[i]);
};
const TOLERANCE = 0.35;
const f = (n) => String(Math.round(n * 10) / 10);
const d = rings
  .map((r) => simplify(r, TOLERANCE))
  .filter((r) => r.length >= 3)
  .map((r) => "M" + r.map(([x, y]) => `${f(x)} ${f(y)}`).join("L") + "Z")
  .join("");

writeFileSync(
  OUT,
  `// Generated by scripts/render-globe-mark.mjs (\`pnpm render-globe-mark\`);
// edit that and re-run it, not this.
import { useId } from "react";

interface GlobeMarkProps {
  className?: string;
}

/**
 * A small vector globe: the Atlantic, lit from the top left. Gradient ids are
 * per instance; the navbar renders desktop and mobile copies at once, and a
 * shared id would resolve to whichever copy is hidden.
 */
export default function GlobeMark({ className = "" }: GlobeMarkProps) {
  const id = useId().replace(/[^a-zA-Z0-9_-]/g, "");
  const ocean = \`\${id}-ocean\`;
  const shade = \`\${id}-shade\`;

  return (
    <svg viewBox="0 0 64 64" aria-hidden className={className}>
      <defs>
        <radialGradient id={ocean} cx="36%" cy="30%" r="75%">
          <stop offset="0%" stopColor="#6F8BE8" />
          <stop offset="55%" stopColor="#3B5BDB" />
          <stop offset="100%" stopColor="#24378F" />
        </radialGradient>
        <radialGradient id={shade} cx="34%" cy="28%" r="80%">
          <stop offset="0%" stopColor="#FFFFFF" stopOpacity="0.28" />
          <stop offset="35%" stopColor="#FFFFFF" stopOpacity="0" />
          <stop offset="70%" stopColor="#05092E" stopOpacity="0" />
          <stop offset="100%" stopColor="#05092E" stopOpacity="0.5" />
        </radialGradient>
      </defs>
      <circle cx="32" cy="32" r="32" fill={\`url(#\${ocean})\`} />
      <path fill="#8FC49F" d="${d}" />
      <circle cx="32" cy="32" r="32" fill={\`url(#\${shade})\`} />
      <circle cx="32" cy="32" r="31.2" fill="none" stroke="#B5C6F8" strokeOpacity="0.55" strokeWidth="1.6" />
    </svg>
  );
}
`,
);
console.log(`Wrote GlobeMark.tsx: ${kept.length} of ${polygons.length} land polygons, path ${(d.length / 1024).toFixed(1)} KB`);
